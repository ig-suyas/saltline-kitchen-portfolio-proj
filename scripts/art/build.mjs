// Writes each dish as a full SVG and one SVG per layer (public/art), the collage
// pieces, the grain tile, and layer metadata for React (lib/art/dishes.ts).
import { writeFileSync, mkdirSync, rmSync } from "node:fs";
import { paperDefs, paperBody } from "./paper.mjs";
import { clams } from "./clams.mjs";
import { porgy } from "./porgy.mjs";
import { tomato } from "./tomato.mjs";
import { cake } from "./cake.mjs";
import { pieces } from "./pieces.mjs";
import { grainPng } from "./grain.mjs";

const grain = grainPng();
const grainUri = `data:image/png;base64,${grain.toString("base64")}`;

const dishes = [clams, porgy, tomato, cake];
const doc = (w, h, label, layers) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"${label ? ` role="img" aria-label="${label}"` : ""}><defs>${paperDefs(w, h, grainUri)}</defs>${paperBody(w, h, layers)}</svg>`;

rmSync("public/art", { recursive: true, force: true });
mkdirSync("lib/art", { recursive: true });
mkdirSync("public/art/pieces", { recursive: true });

for (const d of dishes) {
  mkdirSync(`public/art/${d.id}`, { recursive: true });
  writeFileSync(`public/art/${d.id}.svg`, doc(640, 640, d.name, d.layers.map((l) => l.svg)));
  for (const l of d.layers) writeFileSync(`public/art/${d.id}/${l.id}.svg`, doc(640, 640, "", [l.svg]));
}
for (const p of pieces) {
  const [, , w, h] = p.viewBox.split(" ").map(Number);
  writeFileSync(`public/art/pieces/${p.id}.svg`, doc(w, h, "", [p.svg]));
}

writeFileSync("public/art/grain.png", grain);

const meta = Object.fromEntries(dishes.map((d) => [d.id, { id: d.id, name: d.name, layers: d.layers.map(({ id, label }) => ({ id, label })) }]));
writeFileSync(
  "lib/art/dishes.ts",
  `// Generated by scripts/art/build.mjs. Do not edit by hand.
export type DishLayer = { id: string; label: string };
export type DishArt = { id: string; name: string; layers: DishLayer[] };
export const dishes = ${JSON.stringify(meta, null, 2)} satisfies Record<string, DishArt>;
export type DishId = keyof typeof dishes;
`,
);
console.log("built", dishes.map((d) => d.id).join(", "), "+", pieces.length, "pieces");
